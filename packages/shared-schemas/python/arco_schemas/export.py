"""Export Pydantic models to JSON Schema (+ hazard taxonomy JSON).

Usage:
    python -m arco_schemas.export --out packages/shared-schemas/schema [--check]

Writes:
    <out>/arco.schema.json      one bundle with every model under `$defs`
                                (input for the TypeScript generator)
    <out>/models/<Name>.json    one schema per top-level model, for ad-hoc validation
    <out>/hazard_classes.json   taxonomy with display/behaviour metadata

`--check` exits non-zero if any file on disk differs from what would be written.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter
from pydantic.json_schema import GenerateJsonSchema, models_json_schema

import arco_schemas as s

# Every top-level model that other services or the dashboard consume by name.
TOP_LEVEL_MODELS: tuple[type[BaseModel], ...] = (
    # geo
    s.Point,
    s.LineString,
    s.Polygon,
    s.MultiPolygon,
    # taxonomy
    s.HazardClassInfo,
    # blackboard
    s.Hazard,
    s.RoadEdge,
    s.EdgeHazardLink,
    s.CommunityReport,
    s.SafeZone,
    s.Route,
    s.AgentEvent,
    # vision
    s.CameraGeoref,
    s.TileGeoref,
    s.FeaturePacketHeader,
    s.Detection,
    # telemetry
    s.HardwareInfo,
    s.TelemetrySample,
    s.BenchmarkResult,
    # scenario
    s.Scenario,
    s.TimelineEvent,
    s.CommunityEvent,
    # messages
    s.DetectionsMessage,
    s.HazardEvent,
    s.EdgeEvent,
    s.GraphUpdatedEvent,
    s.ReportEvent,
    s.SafeZoneEvent,
    s.AgentEventMessage,
    s.ClockEvent,
    s.NetworkEvent,
    s.RoutesUpdatedMessage,
    s.TelemetryMessage,
    s.BenchmarkMessage,
    s.BusEnvelope,
)

# Discriminated unions that should exist as named TS types too.
NAMED_UNIONS: dict[str, Any] = {
    "BlackboardMessage": s.BlackboardMessage,
    "TelemetryChannelMessage": s.TelemetryChannelMessage,
    "AnyMessage": s.AnyMessage,
    "Geometry": s.Geometry,
    "HazardGeometry": s.HazardGeometry,
    "Georef": s.Georef,
}


def _dump(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def build_bundle() -> dict[str, Any]:
    """Bundle every model and named union under `$defs`."""
    _, bundle = models_json_schema(
        [(m, "validation") for m in TOP_LEVEL_MODELS],
        ref_template="#/$defs/{model}",
        schema_generator=GenerateJsonSchema,
    )
    defs: dict[str, Any] = dict(bundle["$defs"])
    for name, union in NAMED_UNIONS.items():
        union_schema = TypeAdapter(union).json_schema(ref_template="#/$defs/{model}")
        defs.update(union_schema.pop("$defs", {}))
        union_schema["title"] = name
        defs[name] = union_schema
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://arco.local/schema/arco.schema.json",
        "title": "ArcoSchemaBundle",
        "description": "ARCO shared contracts. Generated by arco_schemas.export; do not edit.",
        "version": s.SCHEMA_VERSION,
        "type": "object",
        "additionalProperties": False,
        "$defs": dict(sorted(defs.items())),
    }


def build_hazard_classes() -> dict[str, Any]:
    return {
        "version": s.SCHEMA_VERSION,
        "classes": [info.model_dump(mode="json") for info in s.HAZARD_CLASSES.values()],
        "macro": [c.value for c in s.MACRO_CLASSES],
        "micro": [c.value for c in s.MICRO_CLASSES],
    }


def build_outputs() -> dict[str, str]:
    """Return {relative_path: file_contents} for everything the exporter writes."""
    out: dict[str, str] = {
        "arco.schema.json": _dump(build_bundle()),
        "hazard_classes.json": _dump(build_hazard_classes()),
    }
    for model in TOP_LEVEL_MODELS:
        schema = model.model_json_schema(ref_template="#/$defs/{model}")
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        out[f"models/{model.__name__}.json"] = _dump(schema)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="verify files are up to date")
    args = parser.parse_args(argv)

    outputs = build_outputs()
    stale: list[str] = []
    for rel, content in outputs.items():
        path = args.out / rel
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    if args.check:
        if stale:
            print("stale schema files (run `make schemas`):", file=sys.stderr)
            for rel in stale:
                print(f"  {rel}", file=sys.stderr)
            return 1
        print(f"schema export up to date ({len(outputs)} files)")
        return 0

    print(f"wrote {len(outputs)} files to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
